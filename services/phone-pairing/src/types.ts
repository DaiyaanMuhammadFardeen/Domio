export const DEFAULT_PAIRING_CAPABILITIES: readonly PairingCapability[] = [
  'advance',
  'retreat',
  'jump',
  'laser',
  'notes',
  'timer',
  'parking_lot',
] as const;

/** Token rotation interval — 60 s per the phase 15 W6 budget. */
export const PAIRING_ROTATION_MS = 60 * 1000;

/** Hard cap on token lifetime — 5 minutes. After this a phone must re-pair. */
export const PAIRING_MAX_TTL_MS = 5 * 60 * 1000;
